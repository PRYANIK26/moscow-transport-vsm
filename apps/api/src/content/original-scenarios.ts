export function getScenario(id: string): Scenario {
  const scenario = scenarios.find((s) => s.id === id);
  if (!scenario) throw new Error('Сценарий не найден');
  return scenario;
}
export function getActions(scenario: Scenario, triggered: string[]): ActionDef[] {
  return [
    ...scenario.actions,
    ...scenario.events
      .filter((e) => triggered.includes(e.id) && e.requiredAction)
      .map((e) => extraActions[e.requiredAction!]),
  ];
}
